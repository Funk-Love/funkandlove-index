// Asset manifest for the ungitted public/ tree: node scripts/gen-asset-manifest.mjs
// The OSS bucket is public-read but not public-list, so contributors need this
// committed index to know what to pull. Rerun after adding or removing assets.
import { readdir, stat, writeFile } from 'node:fs/promises';
import { resolve, relative, posix, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(import.meta.url), '../..');
const publicDir = resolve(root, 'public');
const manifestPath = resolve(root, 'asset-manifest.json');
const BASE_URL = 'https://funk-and.love';

// required    build fails without it (library.json is imported by lib/music.ts,
//             portraits are the sources the preview generators read)
// recommended page looks broken without it, but dev server still boots
// optional    the 1.2 GB promo video; skip it unless you touch VideoPlayer
function tierFor(path) {
  if (path.startsWith('video/')) return 'optional';
  if (path.endsWith('.mp3')) return 'recommended';
  if (path.startsWith('audio/')) return 'required';
  if (path.startsWith('images/leaders/') || path.startsWith('images/members/')) return 'required';
  if (path.startsWith('images/hero/')) return 'required';
  if (!path.includes('/')) return 'required';
  return 'recommended';
}

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = resolve(dir, entry.name);
    if (entry.isDirectory()) files.push(...await walk(full));
    else if (entry.isFile()) files.push(full);
  }
  return files;
}

const found = await walk(publicDir);
const files = [];
for (const full of found) {
  const path = relative(publicDir, full).split(sep).join(posix.sep);
  const { size } = await stat(full);
  files.push({ path, bytes: size, tier: tierFor(path) });
}
files.sort((a, b) => a.path.localeCompare(b.path));

const totals = {};
for (const file of files) {
  const bucket = totals[file.tier] ??= { count: 0, bytes: 0 };
  bucket.count += 1;
  bucket.bytes += file.bytes;
}

await writeFile(manifestPath, JSON.stringify({
  baseUrl: BASE_URL,
  generatedAt: new Date().toISOString().slice(0, 10),
  note: 'Generated by scripts/gen-asset-manifest.mjs. Pull with npm run fetch-assets.',
  totals,
  files,
}, null, 2) + '\n');

const mb = bytes => `${(bytes / 1024 / 1024).toFixed(1)} MB`;
console.log(`asset-manifest.json: ${files.length} files`);
for (const [tier, { count, bytes }] of Object.entries(totals)) {
  console.log(`  ${tier.padEnd(12)} ${String(count).padStart(3)} files  ${mb(bytes)}`);
}
